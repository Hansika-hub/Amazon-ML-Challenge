def extract_unit(series):

    return series.map(
        lambda x:
            (
                match.group(1)
                if (
                    match := UNIT_PATTERN.search(x)
                )
                else np.nan
            )
            if isinstance(x, str)
            else np.nan
    )


def remove_unit(series):

    return series.str.replace(
        UNIT_PATTERN,
        " ",
        regex=True
    ).str.replace(
        WHITESPACE_PATTERN,
        " ",
        regex=True
    ).str.strip()


def extract_numeric_tokens(series):

    return series.map(
        lambda x:
            NUMERIC_TOKEN_RE.findall(x)
            if isinstance(x, str) and x
            else []
    )


