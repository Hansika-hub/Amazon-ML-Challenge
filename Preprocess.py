def preprocess_source(
    df,
    id_col="entity_id"
):

    timings = {}

    total_start = time.perf_counter()

    out = df.copy()

    # --------------------------------------------------------
    # COUNTRY
    # --------------------------------------------------------

    start = time.perf_counter()

    country_normalized = (
        out["country"]
        .fillna("")
        .astype(str)
        .str.strip()
        .str.casefold()
    )

    out["country_normalized"] = (
        country_normalized
    )

    timings["country"] = (
        time.perf_counter() - start
    )

    # --------------------------------------------------------
    # MISSING FLAGS
    # --------------------------------------------------------

    start = time.perf_counter()

    name_raw = out["business_name"]

    address_raw = out["business_address"]

    out["name_is_missing"] = (
        name_raw.isna()
        |
        name_raw.astype(str)
        .str.strip()
        .eq("")
    )

    out["address_is_missing"] = (
        address_raw.isna()
        |
        address_raw.astype(str)
        .str.strip()
        .eq("")
    )

    name_filled = name_raw.fillna("")

    address_filled = address_raw.fillna("")

    timings["missing flags"] = (
        time.perf_counter() - start
    )

    # --------------------------------------------------------
    # RAW EXTRACTION
    # --------------------------------------------------------

    start = time.perf_counter()

    out["domain"] = (
        name_filled.map(
            extract_domain
        )
    )

    out["has_repeated_token"] = (
        repeated_token(
            name_filled
        )
    )

    out["address_numeric_tokens"] = (
        extract_numeric_tokens(
            address_filled
        )
    )

    timings["raw extraction"] = (
        time.perf_counter() - start
    )

    # ========================================================
    # NAME
    # ========================================================

    # --------------------------------------------------------
    # Name normalization
    # --------------------------------------------------------

    start = time.perf_counter()

    name_no_domain = (
        name_filled
        .str.replace(
            EMAIL_RE,
            " ",
            regex=True
        )
        .str.replace(
            URL_RE,
            " ",
            regex=True
        )
    )

    name_clean = basic_clean(
        name_no_domain
    )

    name_clean = (
        name_clean
        .str.replace(
            r"#\w*",
            " ",
            regex=True
        )
        .str.replace(
            WHITESPACE_PATTERN,
            " ",
            regex=True
        )
        .str.strip()
    )

    out["name_normalized"] = (
        apply_suffix_map(
            name_clean
        )
    )

    out["name_suffix_stripped"] = (
        strip_suffixes(
            out["name_normalized"]
        )
    )

    out["name_sorted_tokens"] = (
        sorted_tokens(
            out["name_suffix_stripped"]
        )
    )

    timings["name normalization"] = (
        time.perf_counter() - start
    )

    # --------------------------------------------------------
    # Name transliteration
    #
    # IMPORTANT:
    # Detection + transliteration are now one logical pass.
    # --------------------------------------------------------

    start = time.perf_counter()

    (
        out["name_transliterated"],
        out["script_name"]
    ) = process_transliteration_series(
        out["name_normalized"],
        country_normalized
    )

    out["name_transliterated_suffix_stripped"] = (
        strip_suffixes(
            out["name_transliterated"]
        )
    )

    timings["name transliteration"] = (
        time.perf_counter() - start
    )

    # --------------------------------------------------------
    # Name phonetic
    # --------------------------------------------------------

    start = time.perf_counter()

    out["name_phonetic"] = (
        phonetic_code(
            out["name_transliterated"]
        )
    )

    timings["name phonetic"] = (
        time.perf_counter() - start
    )

    # ========================================================
    # ADDRESS
    # ========================================================

    # --------------------------------------------------------
    # Address normalization
    # --------------------------------------------------------

    start = time.perf_counter()

    address_clean = basic_clean(
        address_filled
    )

    address_clean = apply_street_map(
        address_clean
    )

    out["unit_value"] = (
        extract_unit(
            address_clean
        )
    )

    address_no_unit = remove_unit(
        address_clean
    )

    out["address_normalized"] = (
        address_no_unit
        .str.replace(
            r"#\w*",
            " ",
            regex=True
        )
        .str.replace(
            WHITESPACE_PATTERN,
            " ",
            regex=True
        )
        .str.strip()
    )

    timings["address normalization"] = (
        time.perf_counter() - start
    )

    # --------------------------------------------------------
    # Address transliteration
    # --------------------------------------------------------

    start = time.perf_counter()

    (
        out["address_transliterated"],
        out["script_address"]
    ) = process_transliteration_series(
        out["address_normalized"],
        country_normalized
    )

    timings["address transliteration"] = (
        time.perf_counter() - start
    )

    # --------------------------------------------------------
    # Missing-value cleanup
    # --------------------------------------------------------

    out.loc[
        out["name_is_missing"],
        [
            "name_normalized",
            "name_suffix_stripped",
            "name_sorted_tokens",
            "name_transliterated",
            "name_transliterated_suffix_stripped",
            "name_phonetic",
        ]
    ] = np.nan

    out.loc[
        out["address_is_missing"],
        [
            "unit_value",
            "address_normalized",
            "address_transliterated",
        ]
    ] = np.nan

    missing_addresses = int(
        out["address_is_missing"].sum()
    )

    if missing_addresses:

        out.loc[
            out["address_is_missing"],
            "address_numeric_tokens"
        ] = pd.Series(
            [
                []
                for _ in range(missing_addresses)
            ],
            index=out.index[out["address_is_missing"]]
        )

    # --------------------------------------------------------
    # Final columns
    # --------------------------------------------------------

    final_cols = [
        id_col,

        "business_name",
        "business_address",
        "country",

        "name_is_missing",
        "address_is_missing",

        "script_name",
        "script_address",

        "name_normalized",
        "name_suffix_stripped",
        "name_sorted_tokens",

        "name_transliterated",
        "name_transliterated_suffix_stripped",
        "name_phonetic",

        "address_normalized",
        "address_transliterated",

        "address_numeric_tokens",
        "unit_value",

        "domain",
        "has_repeated_token",

        "country_normalized",
    ]

    final_cols = [
        col
        for col in final_cols
        if col in out.columns
    ]

    result = out[
        final_cols
    ]

    timings["total"] = (
        time.perf_counter() - total_start
    )

    # ========================================================
    # PROFILING
    # ========================================================

    if PROFILE:

        print()
        print(
            "======================================"
        )
        print(
            "       PREPROCESSING TIMING"
        )
        print(
            "======================================"
        )

        for key, value in timings.items():

            print(
                f"{key:30s}: "
                f"{value:9.2f} sec"
            )

        print(
            "======================================"
        )

        print(
            "\nCACHE STATISTICS"
        )

        print(
            "detect_script_fast:",
            detect_script_fast.cache_info()
        )

        print(
            "detect_indic_script_full:",
            detect_indic_script_full.cache_info()
        )

        print(
            "detect_and_transliterate:",
            detect_and_transliterate.cache_info()
        )

        print(
            "transliterate_itrans:",
            transliterate_itrans.cache_info()
        )

        print(
            "transliterate_tamil:",
            transliterate_tamil.cache_info()
        )

        print(
            "transliterate_mixed:",
            transliterate_mixed.cache_info()
        )

    return result

