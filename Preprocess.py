@lru_cache(maxsize=CACHE_SIZE)
def transliterate_itrans(
    text,
    script
):

    if (
        not HAVE_INDIC
        or script not in SANSCRIPT_SCHEME
    ):
        return text

    try:

        source_scheme = getattr(
            sanscript,
            SANSCRIPT_SCHEME[script]
        )

        return sanscript.transliterate(
            text,
            source_scheme,
            sanscript.ITRANS
        ).lower()

    except Exception:

        return text


@lru_cache(maxsize=CACHE_SIZE)
def transliterate_tamil(text):

    if not HAVE_AKSHARAMUKHA:
        return text

    try:

        return aksharamukha_translit.process(
            "Tamil",
            "ISO",
            text
        ).lower()

    except Exception:

        return text

def transliterate_script(
    text,
    script
):

    if not text:
        return text

    if script in (
        "latin",
        "unknown",
        "missing"
    ):
        return text

    if script in SANSCRIPT_SCHEME:

        result = transliterate_itrans(
            text,
            script
        )

        # Tamil transliteration can produce
        # Latin characters with diacritics:
        # ḷ, ō, ṉ, ā, etc.
        #
        # Convert them to plain ASCII:
        # l, o, n, a, etc.
        if script == "tamil":
            result = strip_latin_diacritics(result)

        return result

    if script == "mixed":

        return transliterate_mixed(
            text
        )

    return text


@lru_cache(maxsize=CACHE_SIZE)
def transliterate_mixed(text):

    if not text:
        return text

    output = []

    current_script = None
    buffer = []

    def flush():

        nonlocal buffer
        nonlocal current_script

        if not buffer:
            return

        chunk = "".join(buffer)

        if current_script in (
            "latin",
            "unknown",
            None
        ):

            output.append(chunk)

        else:

            output.append(
                transliterate_script(
                    chunk,
                    current_script
                )
            )

        buffer = []

    for char in text:

        if char.isspace():

            buffer.append(char)
            continue

        script = SCRIPT_BY_CHAR.get(
            char,
            "latin"
        )

        if script != current_script:

            flush()

            current_script = script

        buffer.append(char)

    flush()

    return "".join(output)


