def phonetic_code(series):

    if not HAVE_JELLYFISH:

        return pd.Series(
            np.nan,
            index=series.index
        )

    return series.map(
        lambda x:
            jellyfish.nysiis(x)
            if isinstance(x, str) and x
            else np.nan
    )


def repeated_token(series):

    def check(text):

        if not text:
            return False

        tokens = text.lower().split()

        if len(tokens) < 2:
            return False

        counts = Counter(tokens)

        return any(
            count > 1
            for token, count
            in counts.items()
            if len(token) > 2
        )

    return series.map(check)


