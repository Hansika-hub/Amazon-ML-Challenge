def extract_domain(text):

    if not text:
        return None

    match = EMAIL_RE.search(text)

    if match:
        return match.group(1).lower().rstrip(".")

    match = URL_RE.search(text)

    if match:

        domain = match.group(1).lower().rstrip(".")

        if "." in domain:
            return domain

    return None


