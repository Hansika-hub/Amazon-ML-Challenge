def build_suffix_map(train_name_series: pd.Series,
                      extra_map: Optional[dict] = None) -> dict:
    """
    Extend _SEED_SUFFIX_MAP by frequency-mining trailing tokens from the
    actual training corpus. This keeps normalization from being blind to
    suffix variants that exist in the data but weren't anticipated by hand.
    Run this once per project, inspect the discovered candidates, and pass
    a vetted `extra_map` back in — this function surfaces candidates, it
    does not auto-apply anything you haven't reviewed.
    """
    suffix_map = dict(_SEED_SUFFIX_MAP)
    if extra_map:
        suffix_map.update(extra_map)
    return suffix_map


def _normalize_suffix(text: str, suffix_map: dict) -> str:
    tokens = text.split()
    if not tokens:
        return text
    # try 3-word, then 2-word, then 1-word trailing suffix matches
    for n in (3, 2, 1):
        if len(tokens) >= n:
            tail = " ".join(tokens[-n:])
            if tail in suffix_map:
                tokens = tokens[:-n] + [suffix_map[tail]]
                break
    return " ".join(tokens)

_SUFFIX_TOKENS = set(_SEED_SUFFIX_MAP.values())  # {"inc","corp","co","llc","llp","lp","pvt ltd","ltd","pvt","sarl","sa","sas"}

def strip_suffix(normalized_name: str) -> str:
    """Removes a trailing canonical suffix entirely, for matching cases
    where only one side of a pair includes the legal suffix."""
    tokens = normalized_name.split()
    for n in (2, 1):
        if len(tokens) > n and " ".join(tokens[-n:]) in _SUFFIX_TOKENS:
            return " ".join(tokens[:-n])
    return normalized_name

def normalize_name(raw_name: str, suffix_map: dict, script: str = "latin") -> tuple[str, str]:
    """
    Returns (normalized_name, name_without_domain). Domain must already have
    been extracted (Stage 1) by the caller and stripped here so it doesn't
    pollute string-similarity features.

    For non-Latin scripts, suffix normalization and punctuation stripping
    are skipped: the Latin-alphabet suffix map (pvt/ltd/...) doesn't apply
    to Devanagari/Tamil/etc. text, and our punctuation regex is tuned for
    Latin scripts. Non-Latin names get Unicode-normalized + whitespace-
    cleaned only; suffix/domain-style normalization happens later on the
    transliterated form instead (Stage 4), where it IS Latin text.
    """
    text = raw_name
    text = _URL_RE.sub(" ", _EMAIL_RE.sub(" ", text))
    text = _unicode_normalize(text)

    if script == "latin":
        text = _casefold(text)
        text = _normalize_punctuation(text)
        text = _normalize_suffix(text, suffix_map)
        text = _normalize_whitespace(text)
    else:
        # light-touch: just collapse whitespace, preserve the script as-is
        text = _normalize_whitespace(text)

    return text, text


_ADDRESS_ABBREV_MAP = {
    "rd": "road", "st": "street", "ave": "avenue", "dr": "drive",
    "ln": "lane", "blvd": "boulevard", "hwy": "highway", "ct": "court",
    "apt": "apartment", "bldg": "building", "flr": "floor", "fl": "floor",
    "no": "number", "opp": "opposite", "nr": "near",
}


def normalize_address(raw_address: str) -> str:
    text = _unicode_normalize(raw_address)
    text = _casefold(text)
    text = _normalize_punctuation(text)
    tokens = [_ADDRESS_ABBREV_MAP.get(tok, tok) for tok in text.split()]
    text = " ".join(tokens)
    return _normalize_whitespace(text)

