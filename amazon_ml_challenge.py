def transliterate(text: str, script: str) -> Optional[str]:
    """
    Deterministic, library-based transliteration (not model-based) so it's
    fast enough to run over the full dataset and fully reproducible for the
    methodology write-up. Returns None if the script isn't supported or the
    library isn't installed — callers must keep the original-script field
    regardless, per the earlier discussion: transliteration is an ADDITION,
    never a replacement for the original.
    """
    if not _HAS_INDIC or script not in _SANSCRIPT_SCHEME:
        return None
    try:
        src_scheme = getattr(sanscript, _SANSCRIPT_SCHEME[script])
        return sanscript.transliterate(text, src_scheme, sanscript.ITRANS).lower()
    except Exception:
        return None

try:
    from aksharamukha import transliterate as aksharamukha_translit
    _HAS_AKSHARAMUKHA = True
except ImportError:
    _HAS_AKSHARAMUKHA = False

def transliterate_tamil(text: str) -> Optional[str]:
    if not _HAS_AKSHARAMUKHA:
        return None
    try:
        return aksharamukha_translit.process("Tamil", "ISO", text).lower()
    except Exception:
        return None

_SCRIPT_TO_TRANSLIT_FN = {
    "tamil": transliterate_tamil,
    **{s: (lambda t, s=s: transliterate(t, s)) for s in _SANSCRIPT_SCHEME},
}

def transliterate_mixed(text: str) -> Optional[str]:
    """Splits mixed-script text into runs by script, transliterates each
    non-Latin run with its matching function, leaves Latin runs as-is."""
    if not text:
        return None
    runs, buf, cur_script = [], "", None
    for ch in text:
        s = detect_script(ch) if ch.strip() else cur_script
        if s != cur_script and buf:
            runs.append((cur_script, buf))
            buf = ""
        cur_script = s
        buf += ch
    if buf:
        runs.append((cur_script, buf))

    out = []
    for script, chunk in runs:
        fn = _SCRIPT_TO_TRANSLIT_FN.get(script)
        out.append(fn(chunk) if fn else chunk)
    result = " ".join(p for p in out if p).strip()
    return _normalize_whitespace(result) if result else None

def phonetic_code(text: str) -> Optional[str]:
    """
    Metaphone-style code on the Latin/transliterated text — catches spelling
    drift transliteration alone won't normalize (e.g. 'Sanav' vs 'Saanav').
    """
    if not text or not _HAS_JELLYFISH:
        return None
    try:
        return jellyfish.metaphone(text)
    except Exception:
        return None

@dataclass
class PipelineConfig:
    suffix_map: dict = field(default_factory=lambda: dict(_SEED_SUFFIX_MAP))


def preprocess_source(df: pd.DataFrame, config: Optional[PipelineConfig] = None) -> pd.DataFrame:
    cfg = config or PipelineConfig()
    out = df.copy()

    # ---- Stage 1: structured extraction (on RAW fields) ----
    out["name_domain"] = out["business_name"].apply(extract_domain)
    out["address_domain"] = out["business_address"].apply(extract_domain)
    out["domain"] = out["name_domain"].combine_first(out["address_domain"])
    out["has_repeated_token"] = out["business_name"].apply(has_repeated_token)
    out["address_numeric_tokens"] = out["business_address"].apply(extract_numeric_tokens)

    # ---- Stage 2: script detection (per field, independently) ----
    out["script_name"] = out["business_name"].apply(detect_script)
    out["script_address"] = out["business_address"].apply(detect_script)

    # ---- Stage 3a: name normalization (script-aware, see normalize_name) ----
    out["normalized_name"] = out.apply(
        lambda r: normalize_name(r["business_name"], cfg.suffix_map, r["script_name"])[0],
        axis=1,
    )
    out["normalized_name_no_suffix"] = out["normalized_name"].apply(strip_suffix)
    out["normalized_name_deduped"] = out["normalized_name"].apply(dedupe_repeated_tokens)

    # ---- Stage 3b: address normalization ----
    out["normalized_address"] = out["business_address"].apply(normalize_address)

    # ---- Stage 4: transliteration + phonetic code (non-Latin fields only) ----
    def _translit_field_row(row, text_col, script_col):
      script = row[script_col]
      text = row[text_col]
      if script == "tamil":
          return transliterate_tamil(text)
      if script in _SANSCRIPT_SCHEME:
          return transliterate(text, script)
      if script == "mixed":
          return transliterate_mixed(text)
      return None

    out["translit_name"] = out.apply(lambda r: _translit_field_row(r, "business_name", "script_name"), axis=1)
    out["translit_address"] = out.apply(lambda r: _translit_field_row(r, "business_address", "script_address"), axis=1)

    # light cleanup on the transliterated form only (already Latin-script
    # ASCII from the library, so punctuation/whitespace pass is safe here)
    out["translit_name"] = out["translit_name"].apply(
        lambda t: _normalize_whitespace(_normalize_punctuation(t))
        if isinstance(t, str) and t else None
    )
    out["translit_address"] = out["translit_address"].apply(
        lambda t: _normalize_whitespace(_normalize_punctuation(t))
        if isinstance(t, str) and t else None
    )

    # phonetic code computed on whichever Latin-script text is available:
    # translit_name if we transliterated, else normalized_name directly
    out["phonetic_code"] = out.apply(
        lambda r: phonetic_code(r["translit_name"] or r["normalized_name"]),
        axis=1,
    )
    out["phonetic_code_address"] = out.apply(
        lambda r: phonetic_code(r["translit_address"] or r["normalized_address"]),
        axis=1,
    )

    return out

