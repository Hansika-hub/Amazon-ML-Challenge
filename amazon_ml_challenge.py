_URL_RE = re.compile(
    r"(?:https?://)?(?:www\.)?([a-z0-9][a-z0-9\-]*\.[a-z]{2,}(?:\.[a-z]{2,})?)",
    re.IGNORECASE,
)
_EMAIL_RE = re.compile(r"[\w.+-]+@([\w-]+\.[\w.-]+)")


def extract_domain(text: str) -> Optional[str]:
    """
    Pull an embedded website/email domain out of a name or address field.
    This is one of the strongest available match signals in this dataset
    (e.g. 'SHIVSHAKTI VIDYALAYA ... | www.shivshakti.com', or a bare
    'heassociates.com' used as the entire name) — a shared domain across
    two records from different sources is near-deterministic evidence of
    the same entity, stronger than any string-similarity score.
    """
    if not text:
        return None
    m = _EMAIL_RE.search(text)
    if m:
        return m.group(1).lower().rstrip(".")
    m = _URL_RE.search(text)
    if m:
        domain = m.group(1).lower().rstrip(".")
        # avoid false positives like "Inc." or decimal-looking tokens
        if "." in domain and not domain.replace(".", "").isdigit():
            return domain
    return None


def has_repeated_token(text: str) -> bool:
    """
    Flags scraping/concatenation artifacts like 'Delta Tetlecommunication
    Inc Inc' or 'Keystone Odyssey Odyssey LLC'. We don't silently dedupe at
    the string level (would corrupt legitimately repeated words), but this
    flag + a deduped variant (see dedupe_repeated_tokens) let similarity
    features avoid being depressed by pure noise.
    """
    tokens = text.lower().split()
    if len(tokens) < 2:
        return False
    counts = Counter(tokens)
    return any(c > 1 for tok, c in counts.items() if len(tok) > 2)


def dedupe_repeated_tokens(text: str) -> str:
    """Collapse immediate consecutive duplicate tokens only (safe, local)."""
    tokens = text.split()
    out = []
    for tok in tokens:
        if not out or out[-1].lower() != tok.lower():
            out.append(tok)
    return " ".join(out)


_NUMERIC_TOKEN_RE = re.compile(r"\b\d[\d/\-]*\b")


def extract_numeric_tokens(address: str) -> list[str]:
    """
    Pull building numbers, unit numbers, PIN/ZIP codes etc. as an unordered
    set. Numeric overlap between two addresses is a cheap, high-precision
    blocking signal independent of edit-distance on the full messy string.
    """
    if not address:
        return []
    return _NUMERIC_TOKEN_RE.findall(address)

_SCRIPT_RANGES = {
    "devanagari": (0x0900, 0x097F),
    "tamil": (0x0B80, 0x0BFF),
    "bengali": (0x0980, 0x09FF),
    "telugu": (0x0C00, 0x0C7F),
    "kannada": (0x0C80, 0x0CFF),
    "malayalam": (0x0D00, 0x0D7F),
    "gujarati": (0x0A80, 0x0AFF),
    "gurmukhi": (0x0A00, 0x0A7F),
}


def detect_script(text: str) -> str:
    """
    Cheap, dependency-free Unicode-block detection. Returns the dominant
    non-Latin script if present, else 'latin', else 'unknown' for empty text.
    Must run BEFORE normalization: casefold/NFKC is safe for any script, but
    which transliteration scheme and which suffix-dictionary to apply is
    decided from this result.
    """
    if not text or not text.strip():
        return "unknown"
    counts = Counter()
    for ch in text:
        cp = ord(ch)
        if cp < 128:
            if ch.isalpha():
                counts["latin"] += 1
            continue
        for name, (lo, hi) in _SCRIPT_RANGES.items():
            if lo <= cp <= hi:
                counts[name] += 1
                break
    if not counts:
        return "unknown"
    dominant, dom_count = counts.most_common(1)[0]
    total = sum(counts.values())
    # mixed if no script has a clear majority (e.g. name + embedded domain)
    if dom_count / total < 0.6 and len(counts) > 1:
        return "mixed"
    return dominant

_WHITESPACE_RE = re.compile(r"\s+")
_PUNCT_KEEP_ALNUM_RE = re.compile(r"[^\w\s&/-]", re.UNICODE)


def _unicode_normalize(text: str) -> str:
    return unicodedata.normalize("NFKC", text)


def _casefold(text: str) -> str:
    return text.casefold()


def _normalize_whitespace(text: str) -> str:
    return _WHITESPACE_RE.sub(" ", text).strip()


def _normalize_punctuation(text: str) -> str:
    text = text.replace("&", " and ")
    text = _PUNCT_KEEP_ALNUM_RE.sub(" ", text)
    return _normalize_whitespace(text)


